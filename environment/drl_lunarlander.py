# ==========================================================

def train_ddqn(env, episodes=NUM_EPISODES):

    agent = DDQNAgent(STATE_SIZE, ACTION_SIZE)

    episode_rewards = []
    average_q_values = []
    landing_history = []
    thruster_history = []

    validation_states = []

    obs, info = env.reset(seed=SEED)

    for _ in range(100):
        validation_states.append(obs.copy())
        action = env.action_space.sample()
        obs, _, terminated, truncated, _ = env.step(action)

        if terminated or truncated:
            obs, info = env.reset()

    validation_states = np.array(validation_states)

    for episode in tqdm(range(episodes)):

        state, info = env.reset(seed=SEED + episode)

        done = False
        episode_reward = 0
        thruster_count = 0

        while not done:

            action = agent.select_action(state)

            if action in [1, 2, 3]:
                thruster_count += 1

            next_state, reward, terminated, truncated, info = env.step(action)

            done = terminated or truncated

            agent.store_experience(
                state,
                action,
                reward,
                next_state,
                done
            )

            agent.train()

            episode_reward += reward

            state = next_state

        episode_rewards.append(episode_reward)
        thruster_history.append(thruster_count)

        safe_landing = (
            terminated
            and not truncated
            and next_state[6] == 1
            and next_state[7] == 1
            and abs(next_state[2]) < 0.10
            and abs(next_state[3]) < 0.10
            and abs(next_state[4]) < 0.10
        )

        landing_history.append(1 if safe_landing else 0)

        with torch.no_grad():
            states = torch.FloatTensor(validation_states).to(DEVICE)
            q_values = agent.q_network(states)
            average_q_values.append(
                q_values.max(1)[0].mean().item()
            )

    return (
        agent,
        episode_rewards,
        average_q_values,
        landing_history,
        thruster_history
    )

