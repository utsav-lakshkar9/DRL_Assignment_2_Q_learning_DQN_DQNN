        dones = torch.FloatTensor(dones).unsqueeze(1).to(DEVICE)

        # --------------------------------------------------
        # Current Q-values
        # --------------------------------------------------
        current_q = self.q_network(states).gather(1, actions)

        # --------------------------------------------------
        # Target Q-values (DQN)
        # --------------------------------------------------
        with torch.no_grad():

            next_q = self.target_network(next_states).max(1)[0].unsqueeze(1)

